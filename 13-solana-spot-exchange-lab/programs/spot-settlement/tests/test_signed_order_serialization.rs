#[test]
fn signed_order_side_tag_is_part_of_the_signed_bytes() {
    let bid = golden_order(spot_settlement::SignedOrderSide::Bid).signing_preimage();
    let ask = golden_order(spot_settlement::SignedOrderSide::Ask).signing_preimage();

    assert_eq!(bid.len(), 138);
    assert_eq!(ask.len(), 138);
    assert_eq!(bid[105], 0);
    assert_eq!(ask[105], 1);
    assert_ne!(Sha256::digest(&bid), Sha256::digest(&ask));
}
