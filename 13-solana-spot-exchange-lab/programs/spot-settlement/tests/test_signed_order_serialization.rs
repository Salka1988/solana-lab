use anchor_lang::prelude::Pubkey;
use sha2::{Digest, Sha256};

fn golden_order(side: spot_settlement::SignedOrderSide) -> spot_settlement::SignedOrderPayload {
    spot_settlement::SignedOrderPayload {
        order_id: 0x0102_0304_0506_0708,
        market_config: Pubkey::new_from_array([0x11; 32]),
        trader: Pubkey::new_from_array([0x22; 32]),
        side,
        price: 0x1112_1314_1516_1718,
        quantity: 0x2122_2324_2526_2728,
        nonce: 0x3132_3334_3536_3738,
        expiry_slot: 0x4142_4344_4546_4748,
    }
}

